const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const express = require('express');
const http = require('node:http');
const jwt = require('jsonwebtoken');

test('authenticated drivers publish independent live bus locations and freshness states', async () => {
  const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'trackmybus-tracking-'));
  process.env.TRACKMYBUS_DB_PATH = path.join(tempDir, 'tracking-test.sqlite');
  require('dotenv').config({ path: path.resolve(__dirname, '../.env') });
  const dbModule = require('../db');
  const { JWT_SECRET } = require('../routes/auth');
  const trackingRouter = require('../routes/tracking');
  const db = await dbModule.initDb().then(() => dbModule.getDb());
  const app = express();
  app.use(express.json());
  app.set('io', { emit() {} });
  app.use('/api/tracking', trackingRouter);
  const server = http.createServer(app);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const baseUrl = `http://127.0.0.1:${server.address().port}/api/tracking`;

  const createDriver = async (name, email, busNumber, route) => {
    const result = await db.run(
      "INSERT INTO users (name, username, password, role, is_approved, bus_number, assigned_route) VALUES (?, ?, 'test', 'driver', 1, ?, ?)",
      [name, email, busNumber, route]
    );
    const token = jwt.sign({ id: result.lastID, username: email, name, role: 'driver' }, JWT_SECRET, { expiresIn: '2m' });
    return { id: String(result.lastID), token };
  };
  const request = async (endpoint, token, body) => {
    const response = await fetch(`${baseUrl}${endpoint}`, {
      method: body === undefined ? 'GET' : 'POST',
      headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(body === undefined ? {} : { 'Content-Type': 'application/json' }) },
      ...(body === undefined ? {} : { body: JSON.stringify(body) })
    });
    return { response, payload: await response.json() };
  };

  try {
    const driverA = await createDriver('Driver A', 'a@example.test', 'BUS-A', 'Station to College');
    const driverB = await createDriver('Driver B', 'b@example.test', 'BUS-B', 'Market to Bus Stand');
    const passengerToken = jwt.sign({ id: 999, username: 'p@example.test', role: 'passenger' }, JWT_SECRET);

    assert.equal((await request('/start', null, {})).response.status, 401, 'tracking start rejects unauthenticated users');
    assert.equal((await request('/start', passengerToken, {})).response.status, 403, 'tracking start rejects passenger tokens');
    assert.equal((await request('/start', driverA.token, {})).response.status, 200);
    assert.equal((await request('/start', driverB.token, {})).response.status, 200);

    const badGps = await request('/location', driverA.token, { latitude: 200, longitude: 74.6 });
    assert.equal(badGps.response.status, 400, 'invalid coordinates are rejected');

    const firstLocation = await request('/location', driverA.token, {
      latitude: 26.4388, longitude: 74.6995, accuracy: 8, speed: 4.2, heading: 90,
      driver_id: driverB.id, bus_number: 'BUS-B'
    });
    assert.equal(firstLocation.response.status, 200);
    assert.equal(firstLocation.payload.location.bus_number, 'BUS-A', 'the server ignores bus identity supplied by the client');
    assert.equal(firstLocation.payload.location.driver_id, driverA.id);
    assert.ok(Number.isFinite(Date.parse(firstLocation.payload.location.updated_at)), 'timestamp is generated by the server');

    await request('/location', driverB.token, { latitude: 26.45, longitude: 74.64, accuracy: 12 });
    let buses = (await request('/active-buses')).payload;
    assert.equal(buses.length, 2, 'both concurrently tracking buses are public');
    assert.equal(buses.find(bus => bus.bus_number === 'BUS-A').status_code, 'LIVE');
    assert.equal(buses.find(bus => bus.bus_number === 'BUS-B').status_code, 'LIVE');
    assert.equal(buses.find(bus => bus.bus_number === 'BUS-A').latitude, 26.4388);

    await db.run("UPDATE bus_locations SET last_update = ?, last_heartbeat_at = ? WHERE bus_number = 'BUS-B'", [new Date(Date.now() - 20000).toISOString(), new Date().toISOString()]);
    buses = (await request('/active-buses')).payload;
    assert.equal(buses.find(bus => bus.bus_number === 'BUS-B').status_code, 'LIVE', 'normal GPS sampling gaps remain live');
    await db.run("UPDATE bus_locations SET last_update = ?, last_heartbeat_at = ? WHERE bus_number = 'BUS-B'", [new Date(Date.now() - 45000).toISOString(), new Date().toISOString()]);
    buses = (await request('/active-buses')).payload;
    assert.equal(buses.find(bus => bus.bus_number === 'BUS-B').status_code, 'DELAYED');
    await db.run("UPDATE bus_locations SET last_update = ?, last_heartbeat_at = ? WHERE bus_number = 'BUS-B'", [new Date(Date.now() - 100000).toISOString(), new Date().toISOString()]);
    buses = (await request('/active-buses')).payload;
    assert.equal(buses.find(bus => bus.bus_number === 'BUS-B').status_code, 'STALE');

    const stopped = await request('/stop', driverA.token, {});
    assert.equal(stopped.payload.tracking_status, 'INACTIVE');
    buses = (await request('/active-buses')).payload;
    assert.equal(buses.find(bus => bus.bus_number === 'BUS-A').status_code, 'OFFLINE');
    assert.equal(buses.find(bus => bus.bus_number === 'BUS-A').latitude, 26.4388, 'offline records retain only the last known coordinates');

    await db.run("UPDATE bus_locations SET last_heartbeat_at = ? WHERE bus_number = 'BUS-B'", [new Date(Date.now() - 130000).toISOString()]);
    buses = (await request('/active-buses')).payload;
    assert.equal(buses.find(bus => bus.bus_number === 'BUS-B').status_code, 'OFFLINE', 'expired heartbeats are offline');
  } finally {
    await new Promise(resolve => server.close(resolve));
    await db.close();
    delete process.env.TRACKMYBUS_DB_PATH;
    fs.rmSync(tempDir, { recursive: true, force: true });
  }
});
